/* ==========================================================================
   Catalog database — SQLite running in the browser via sql.js (WASM).
   Loaded by both the storefront and the admin panel.

   The database is built in memory from catalog.sql, the text file published
   with the site. There is no server: catalog.sql IS the source of truth.
   ========================================================================== */

const SQLJS_VERSION = '1.10.3';
const SQLJS_BASE = `https://cdn.jsdelivr.net/npm/sql.js@${SQLJS_VERSION}/dist/`;
const CATALOG_URL = './catalog.sql';
const DRAFT_KEY = 'alexstore.catalogDraft';

const Catalog = (() => {
  let db = null;
  let sql = null;

  /** Boot sql.js and build the in-memory database. */
  async function init() {
    if (db) return db;

    sql = await initSqlJs({ locateFile: (file) => SQLJS_BASE + file });

    const source = await loadCatalogSource();
    db = new sql.Database();
    db.run(source);

    // Guard against a malformed catalog silently producing an empty site.
    const { count } = one('SELECT COUNT(*) AS count FROM products');
    if (!count) throw new Error('Catalog loaded but contains no products');

    return db;
  }

  /**
   * A local draft (if the owner has made edits in the admin panel) wins over
   * the published catalog, so this machine previews unpublished changes.
   */
  async function loadCatalogSource() {
    try {
      const res = await fetch(CATALOG_URL, { cache: 'no-cache' });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.text();
    } catch (err) {
      const draft = localStorage.getItem(DRAFT_KEY);
      if (draft) {
        console.warn('catalog.sql unreachable, using local draft:', err);
        return draft;
      }
      throw new Error(`Could not load catalog.sql (${err.message})`);
    }
  }

  /** True when this browser holds unpublished edits. */
  function hasDraft() {
    return Boolean(localStorage.getItem(DRAFT_KEY));
  }

  /** Rebuilds catalog.sql text from the live database. */
  function toSql() {
    const rows = all('SELECT * FROM products ORDER BY sort_order, id');
    const settings = all('SELECT * FROM settings ORDER BY key');

    const escape = (v) =>
      v === null || v === undefined
        ? 'NULL'
        : `'${String(v).replace(/'/g, "''")}'`;

    const productLines = rows
      .map(
        (p) =>
          `  (${escape(p.slug)}, ${escape(p.name)}, ${escape(p.category)}, ` +
          `${p.price_cents}, ${escape(p.currency)}, ${escape(p.image_url)}, ` +
          `${escape(p.tint)}, ${p.in_stock ? 1 : 0}, ${p.sort_order})`,
      )
      .join(',\n');

    const settingLines = settings
      .map((s) => `  (${escape(s.key)}, ${escape(s.value)})`)
      .join(',\n');

    return `-- Generated by admin.html — replace catalog.sql with this file and push.
-- Prices are whole cents. Regenerated ${new Date().toISOString()}

CREATE TABLE IF NOT EXISTS products (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  slug        TEXT    NOT NULL UNIQUE,
  name        TEXT    NOT NULL,
  category    TEXT    NOT NULL DEFAULT 'General',
  price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
  currency    TEXT    NOT NULL DEFAULT 'USD',
  image_url   TEXT,
  tint        TEXT,
  in_stock    INTEGER NOT NULL DEFAULT 1 CHECK (in_stock IN (0, 1)),
  sort_order  INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_products_sort ON products (sort_order, id);

CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);

INSERT OR IGNORE INTO settings (key, value) VALUES
${settingLines};

INSERT INTO products (slug, name, category, price_cents, currency, image_url, tint, in_stock, sort_order) VALUES
${productLines}
ON CONFLICT (slug) DO UPDATE SET
  name        = excluded.name,
  category    = excluded.category,
  price_cents = excluded.price_cents,
  currency    = excluded.currency,
  image_url   = excluded.image_url,
  tint        = excluded.tint,
  in_stock    = excluded.in_stock,
  sort_order  = excluded.sort_order;
`;
  }

  /** Persists the current database as this browser's unpublished draft. */
  function saveDraft() {
    localStorage.setItem(DRAFT_KEY, toSql());
  }

  function clearDraft() {
    localStorage.removeItem(DRAFT_KEY);
  }

  /* --------------------------------------------------------------- queries */

  function all(sqlText, params = []) {
    const stmt = db.prepare(sqlText);
    stmt.bind(params);
    const rows = [];
    while (stmt.step()) rows.push(stmt.getAsObject());
    stmt.free();
    return rows;
  }

  function one(sqlText, params = []) {
    return all(sqlText, params)[0] ?? null;
  }

  function run(sqlText, params = []) {
    const stmt = db.prepare(sqlText);
    stmt.bind(params);
    stmt.step();
    stmt.free();
  }

  /* ---------------------------------------------------------------- model */

  function listProducts() {
    return all('SELECT * FROM products ORDER BY sort_order ASC, id ASC');
  }

  function getSetting(key) {
    return one('SELECT value FROM settings WHERE key = ?', [key])?.value ?? null;
  }

  function slugify(name) {
    return String(name)
      .toLowerCase()
      .normalize('NFKD')
      .replace(/[^a-z0-9\s-]/g, '')
      .trim()
      .replace(/\s+/g, '-')
      .replace(/-+/g, '-')
      .slice(0, 80);
  }

  /** Validates a payload; returns {ok:true, value} or {ok:false, errors}. */
  function validate(input) {
    const errors = {};

    const name = typeof input.name === 'string' ? input.name.trim() : '';
    if (!name || name.length > 120) errors.name = 'Required, max 120 characters';

    const price = Number(input.price_cents);
    if (!Number.isInteger(price) || price < 0) {
      errors.price_cents = 'Must be whole cents, e.g. 2800 for $28.00';
    }

    const category =
      typeof input.category === 'string' && input.category.trim()
        ? input.category.trim().slice(0, 60)
        : 'General';

    let currency = 'USD';
    if (input.currency) {
      currency = String(input.currency).trim().toUpperCase();
      if (!/^[A-Z]{3}$/.test(currency)) errors.currency = 'Must be a 3-letter code';
    }

    const requested = typeof input.slug === 'string' ? input.slug.trim().toLowerCase() : '';
    const slug = requested || slugify(name);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
      errors.slug = 'Lowercase letters, numbers and single dashes only';
    }

    const imageUrl =
      typeof input.image_url === 'string' && input.image_url.trim() ? input.image_url.trim() : null;
    if (imageUrl && !/^https?:\/\//i.test(imageUrl)) errors.image_url = 'Must be an http(s) URL';

    if (Object.keys(errors).length) return { ok: false, errors };

    return {
      ok: true,
      value: {
        slug,
        name,
        category,
        price_cents: price,
        currency,
        image_url: imageUrl,
        tint: typeof input.tint === 'string' && input.tint.trim() ? input.tint.trim() : null,
        in_stock: input.in_stock === false || input.in_stock === 0 ? 0 : 1,
        sort_order: Number.isInteger(Number(input.sort_order)) ? Number(input.sort_order) : 0,
      },
    };
  }

  function slugTaken(slug, exceptId = null) {
    const row = exceptId
      ? one('SELECT id FROM products WHERE slug = ? AND id <> ?', [slug, exceptId])
      : one('SELECT id FROM products WHERE slug = ?', [slug]);
    return Boolean(row);
  }

  function createProduct(input) {
    const { ok, errors, value } = validate(input);
    if (!ok) return { ok: false, errors };
    if (slugTaken(value.slug)) return { ok: false, errors: { slug: 'Already in use' } };

    run(
      `INSERT INTO products (slug, name, category, price_cents, currency, image_url, tint, in_stock, sort_order)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [value.slug, value.name, value.category, value.price_cents, value.currency,
       value.image_url, value.tint, value.in_stock, value.sort_order],
    );
    saveDraft();
    return { ok: true, value };
  }

  function updateProduct(id, input) {
    const { ok, errors, value } = validate(input);
    if (!ok) return { ok: false, errors };
    if (slugTaken(value.slug, id)) return { ok: false, errors: { slug: 'Already in use' } };

    run(
      `UPDATE products
          SET slug = ?, name = ?, category = ?, price_cents = ?, currency = ?,
              image_url = ?, tint = ?, in_stock = ?, sort_order = ?
        WHERE id = ?`,
      [value.slug, value.name, value.category, value.price_cents, value.currency,
       value.image_url, value.tint, value.in_stock, value.sort_order, id],
    );
    saveDraft();
    return { ok: true, value };
  }

  function deleteProduct(id) {
    run('DELETE FROM products WHERE id = ?', [id]);
    saveDraft();
  }

  /** Settings that the published catalog should carry. */
  function setSetting(key, value) {
    run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value',
        [key, value]);
    saveDraft();
  }

  return {
    init,
    listProducts,
    getSetting,
    slugify,
    createProduct,
    updateProduct,
    deleteProduct,
    setSetting,
    toSql,
    saveDraft,
    clearDraft,
    hasDraft,
  };
})();